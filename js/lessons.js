// Helper to find lesson by id
window.getLessonById = function(lessonId) {
    for (const unit of window.TYPING_COURSES) {
        for (let i = 0; i < unit.lessons.length; i++) {
            if (unit.lessons[i].id === lessonId) {
                const nextLesson = unit.lessons[i + 1] || null;
                return { lesson: unit.lessons[i], unit, nextLesson };
            }
        }
    }
    return null;
};
